def combin(n, k):
    """
    рекурсивное вычисление числа сочетаний C(n, k) = n! / (k! * (n-k)!)

    используется рекуррентное соотношение:
    C(n, k) = C(n-1, k-1) + C(n-1, k)

    аргументы:
        n : общее количество элементов (n >= 0)
        k : количество выбираемых элементов (0 <= k <= n)
    
    возвращает:
        число сочетаний C(n, k)
    """
    # базовые случаи: C(n, 0) = 1 и C(n, n) = 1
    if k == 0 or k == n:
        return 1

    # рекурсивный случай по паскалю
    return combin(n - 1, k - 1) + combin(n - 1, k)


print(combin(5, 2))
