def odd_list(a, n):
    """
    рекурсивное создание списка четных значений из исходного списка.
    
    аргументы:
        a : список целых чисел
        n : количество элементов в списке
    
    возвращает:
        новый список, содержащий только четные элементы
    """
    if n == 0:
        return []

    result = odd_list(a, n - 1)

    # проверяем n-й элемент (индекс n-1) на четность
    if a[n - 1] % 2 == 0:
        result.append(a[n - 1])

    return result


print(odd_list([1, 2, 3, 4, 5], 5))
