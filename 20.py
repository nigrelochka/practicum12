def comp(a, b, m, n):
    """
    Нахождение длины наибольшей общей подпоследовательности двух строк.

    Аргументы:
        a : первая строка
        b : вторая строка
        m : длина первой строки (кол-во символов)
        n : длина второй строки (кол-во символов)
    """
    if m == 0 or n == 0:
        return 0

    if a[m - 1] == b[n - 1]:
        return 1 + comp(a, b, m - 1, n - 1)

    # если последние символы не совпадают, берем максимум из двух вариантов
    return max(comp(a, b, m - 1, n), comp(a, b, m, n - 1))


# Примеры использования
if __name__ == "__main__":
    # Тестовые примеры
    a, b = "ABCDGH", "AEDFHR"
    print(f"LCS('{a}', '{b}') = {comp(a, b, len(a), len(b))}")